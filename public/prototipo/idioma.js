const languageButtons = document.querySelectorAll("[data-language]");
let language = new URLSearchParams(location.search).get("lang") === "pt" ? "pt" : "en";
const translate = text => language === "en" ? (english[text] ?? text) : text;
const sourceNodes = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
for (let node = walker.nextNode(); node; node = walker.nextNode()) {
  if (Object.hasOwn(english, node.data.trim())) sourceNodes.push([node, node.data]);
}
const sourceLabels = [...document.querySelectorAll("[aria-label]")].map(node => [node, node.getAttribute("aria-label")]);

function renderLanguage() {
  document.documentElement.lang = language === "en" ? "en" : "pt-PT";
  document.title = translate("EVDCGrid — Micro-redes DC");
  for (const [node, source] of sourceNodes) node.data = source.replace(source.trim(), translate(source.trim()));
  for (const [node, source] of sourceLabels) node.setAttribute("aria-label", translate(source));
  for (const button of languageButtons) button.setAttribute("aria-pressed", String(button.dataset.language === language));
}
renderLanguage();
